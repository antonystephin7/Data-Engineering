SELECT STUDENT_NAME AS NAME FROM STUDENTS;
SELECT EMPLOYEE_NAME AS NAME FROM EMPLOYEES;
SELECT SALARY AS EMP_SALARY FROM EMPLOYEES;
SELECT PRODUCT_NAME AS NAME FROM PRODUCTS;
SELECT PRICE AS PRODUCT_PRICE FROM PRODUCTS;
SELECT TITLE AS BOOK_NAME FROM BOOKS;
SELECT COURSE_NAME AS C_NAME FROM COURSES;
SELECT CUSTOMER_NAME AS CUST_NAME FROM CUSTOMERS;
SELECT DEPARTMENT AS DEPT_NAME FROM EMPLOYEES;
SELECT DESIGNATION AS JOB_ROLE FROM EMPLOYEES;
SELECT JOINING_DATE AS DOJ FROM EMPLOYEES;
SELECT QUANTITY AS STOCK FROM PRODUCTS;
SELECT EMAIL AS EMAIL_ID FROM STUDENTS;
SELECT MOBILE_NUMBER AS PHONE FROM STUDENTS;
SELECT AUTHOR AS BOOK_AUTHOR FROM BOOKS;
SELECT BRAND AS BRAND_NAME FROM CUSTOMERS;
SELECT SALARY, (SALARY * 12) AS ANNUAL_SALARY FROM EMPLOYEES;
SELECT SALARY, (SALARY * 1.10) AS INCREMENTAL_SALARY FROM EMPLOYEES;
SELECT SALARY, (SALARY * 0.85) AS DEDUCTION FROM EMPLOYEES;
SELECT PRICE, (PRICE * QUANTITY) AS TOTAL_VALUE FROM PRODUCTS;
SELECT PRICE, (PRICE * 0.90) AS DISCOUNTED_PRICE FROM PRODUCTS;
SELECT PRICE, (PRICE * 1.18) AS FINAL_PRICE FROM PRODUCTS;
SELECT PRICE, (PRICE * 0.20) AS DISCOUNTED_PRICE FROM BOOKS;
SELECT FEES, (FEES * 0.85) AS FINAL_FEES FROM COURSES;
SELECT AGE, (AGE + 1) AS NEXT_YEAR_AGE FROM STUDENTS;
SELECT SALARY, (SALARY / 12) AS MONTHLY_SALARY FROM EMPLOYEES;
SELECT PRODUCT_NAME, PRICE, QUANTITY, (PRICE * QUANTITY) AS TOTAL_VALUE FROM PRODUCTS;
SELECT LENGTH(STUDENT_NAME) AS LENGTH_NAME FROM STUDENTS;
SELECT UPPER(EMPLOYEE_NAME) AS UPPER_NAME FROM EMPLOYEES;
SELECT LOWER(PRODUCT_NAME) AS LOWER_PRODUCT FROM PRODUCTS;
SELECT CONCAT("FIRST_NAME", " ", "LAST_NAME") AS FULL_NAME FROM STUDENTS;
SELECT DATE_ADD("JOINING_DATE", INTERVAL 126 DAY) AS FUTURE_DATE FROM EMPLOYEES;
SELECT DATE_SUB("JOINING_DATE", INTERVAL 46 DAY) AS PREVIOUS_DATE FROM EMPLOYEES;
SELECT COUNT(*) AS TOTAL_STUDENTS FROM STUDENTS;
SELECT COUNT(*) AS TOTAL_EMPLOYEES FROM EMPLOYEES;
SELECT COUNT(*) AS TOTAL_PRODUCTS FROM PRODUCTS;
SELECT SUM(SALARY) AS TOTAL_SALARY FROM EMPLOYEES;
SELECT AVG(SALARY) AS AVERAGE_SALARY FROM EMPLOYEES;
SELECT MAX(SALARY) AS MAXIMUM_SALARY FROM EMPLOYEES;
SELECT MIN(SALARY) AS MINIMUM_SALARY FROM EMPLOYEES;
SELECT SUM(STOCK) AS TOTAL_STOCK FROM PRODUCTS;
SELECT AVG(PRICE) AS AVERAGE_PRICE FROM PRODUCTS;
SELECT MAX(PRICE) AS HIGHEST_PRICE FROM PRODUCTS;
SELECT MIN(PRICE) AS LOWEST_PRICE FROM PRODUCTS;
SELECT SUM(FEES) AS TOTAL_COURSE_FEES FROM COURSES;
SELECT AVG(FEES) AS AVERAGE_COURSE_FEES FROM COURSES;
SELECT MAX(FEES) AS MAXIMUM_COURSE_FEE FROM COURSES;
SELECT MIN(FEES) AS MINIMUM_COURSE_FEE FROM COURSES;
SELECT SUM(QUANTITY) AS TOTAL_BOOKS FROM BOOKS;
SELECT AVG(PRICE) AS AVERAGE_BOOK_PRICE FROM BOOKS;
SELECT MAX(PRICE) AS MAXIMUM_BOOK_PRICE FROM BOOKS;
SELECT MIN(PRICE) AS MINIMUM_BOOK_PRICE FROM BOOKS;
SELECT E.EMPLOYEE_NAME, E.SALARY FROM EMPLOYEES AS E;
SELECT S.STUDENT_NAME, S.DEPARTMENT FROM STUDENTS AS S;
SELECT P.PRODUCT_NAME, P.PRICE FROM PRODUCTS AS P;
SELECT B.BOOK_NAME, B.PRICE FROM BOOKS AS B;
SELECT C.COURSE_NAME, C.FEES FROM COURSES AS C;
SELECT CU.CUSTOMER_NAME, CU.CITY FROM CUSTOMERS AS CU;
SELECT E.EMPLOYEE_NAME, E.SALARY FROM EMPLOYEES AS E WHERE E.SALARY > 50000;
SELECT P.PRODUCT_NAME, P.PRICE FROM PRODUCTS AS P WHERE P.PRICE > 10000;
