DELIMITER $$
CREATE FUNCTION CalculateGrade(marks INT)
RETURNS VARCHAR(10)
DETERMINISTIC
BEGIN
    RETURN CASE
        WHEN marks >= 90 THEN 'A'
        WHEN marks >= 75 THEN 'B'
        WHEN marks >= 50 THEN 'C'
        ELSE 'Fail'
    END;
END $$
DELIMITER;
SELECT CalculateGrade(85);
