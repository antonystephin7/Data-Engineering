CREATE FUNCTION EvenOdd(n INT)
RETURNS VARCHAR(10)
DETERMINISTIC
BEGIN
    IF MOD(n, 2) = 0 THEN
        RETURN 'Even';
    ELSE
        RETURN 'Odd';
    END IF;
END $$
DELIMITER;
SELECT EvenOdd(7);

