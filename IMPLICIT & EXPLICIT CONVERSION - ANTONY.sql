-- IMPLICIT CONVERSION: ADD A NUMERIC STRING TO AN INTEGER
SELECT '100' + 50 AS RESULT;

-- IMPLICIT CONVERSION BETWEEN A STRING AND A NUMERIC VALUE
SELECT '25' * 4 AS RESULT;

-- CONVERT A STRING INTO A DATE EXPLICITLY
SELECT CAST('2026-08-31' AS DATE) AS CONVERTED_DATE;

-- CONVERT A NUMBER INTO A CHAR VALUE EXPLICITLY
SELECT CAST(25000 AS CHAR) AS CONVERTED_VALUE;

-- CONVERT A STRING INTO A DECIMAL VALUE EXPLICITLY
SELECT CAST('1250.75' AS DECIMAL(10,2)) AS CONVERTED_VALUE;

-- CONVERT A DATE INTO A FORMATTED CHARACTER VALUE
SELECT DATE_FORMAT('2026-08-31', '%D-%M-%Y') AS FORMATTED_DATE;

-- CONVERT A STRING INTO A DATETIME EXPLICITLY
SELECT CAST('2026-08-31 15:30:00' AS DATETIME) AS CONVERTED_DATETIME;